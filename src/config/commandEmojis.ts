export const commandEmojis = commandPixelEmojis;
export type CommandEmoji = keyof typeof commandEmojis;

export function getCommandEmoji(
  command: string,
  subcommand?: string,
  subcommandGroup?: string,
): string {
  const candidates = [
    [command, subcommandGroup, subcommand].filter(Boolean).join(' ').toLowerCase(),
    [command, subcommand].filter(Boolean).join(' ').toLowerCase(),
    [command, subcommandGroup].filter(Boolean).join(' ').toLowerCase(),
    command.toLowerCase(),
  ];
  const pixelName = candidates
    .map((candidate) =>
      Object.prototype.hasOwnProperty.call(commandPixelEmojis, candidate)
        ? commandPixelEmojis[candidate as CommandEmoji]
        : undefined,
    )
    .find((candidate) => candidate !== undefined);

  return getPixelEmoji(pixelName ?? 'robot') ?? getPixelEmoji('robot') ?? '🤖';
}

export function withEmoji(emoji: CommandEmoji | string, description: string): string {
  const commandName = Object.prototype.hasOwnProperty.call(commandPixelEmojis, emoji) ? emoji : undefined;
  const emojiString = commandName
    ? getCommandEmoji(commandName)
    : getPixelEmoji(String(emoji)) ?? String(emoji);
  return `${emojiString} ${description}`;
}
